//! The design table: the plan and its modelled result for every resistance.

use core::fmt::{self, Write};

use aed_types::{Micros, Ohms, PatientMode, ShockPlan, MAX_PATIENT_OHMS, MIN_PATIENT_OHMS};

use crate::config::WaveformConfig;
use crate::model::{discharge, DischargeResult};
use crate::planner::{plan_with, LimitHit};

/// Spacing of the rows in the design table, in ohms.
pub const TABLE_STEP_OHMS: u16 = 5;

/// One row of the design table: one mode, one patient resistance.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct DesignRow {
    /// Adult or child.
    pub mode: PatientMode,
    /// Patient resistance for this row.
    pub ohms: Ohms,
    /// The plan the planner chose.
    pub plan: ShockPlan,
    /// What the model says that plan does.
    pub result: DischargeResult,
    /// The mode's target delivered energy, in joules.
    pub target_j: f64,
    /// Delivered minus target, as a fraction of target (+0.05 is 5% over).
    pub error_fraction: f64,
    /// Whether the error is inside the configured tolerance.
    pub within_tolerance: bool,
    /// The limit the planner ran into, if any.
    pub limit: Option<LimitHit>,
}

/// Plan and model one row. `None` if the resistance is out of range or the
/// configuration cannot describe a circuit.
#[must_use]
pub fn design_row(config: &WaveformConfig, mode: PatientMode, ohms: Ohms) -> Option<DesignRow> {
    let planned = plan_with(config, mode, ohms).ok()?;
    let result = discharge(&planned.plan, f64::from(ohms.0), config)?;
    let target_j = WaveformConfig::target_joules(mode);
    let error_fraction = (result.patient_energy_j - target_j) / target_j;
    Some(DesignRow {
        mode,
        ohms,
        plan: planned.plan,
        result,
        target_j,
        error_fraction,
        within_tolerance: libm::fabs(error_fraction) <= config.energy_tolerance,
        limit: planned.limit,
    })
}

/// Every row of the design table: adult then child, 25 to 175 Ω in
/// [`TABLE_STEP_OHMS`] steps. Needs no heap.
pub fn design_table(config: &WaveformConfig) -> impl Iterator<Item = DesignRow> + '_ {
    [PatientMode::Adult, PatientMode::Child]
        .into_iter()
        .flat_map(move |mode| {
            (MIN_PATIENT_OHMS.0..=MAX_PATIENT_OHMS.0)
                .step_by(usize::from(TABLE_STEP_OHMS))
                .filter_map(move |r| design_row(config, mode, Ohms(r)))
        })
}

fn ms(t: Micros) -> f64 {
    f64::from(t.0) / 1000.0
}

fn mode_name(mode: PatientMode) -> &'static str {
    match mode {
        PatientMode::Adult => "Adult",
        PatientMode::Child => "Child",
    }
}

/// Write the whole design report (the content of `DESIGN_TABLE.md`) as
/// Markdown.
///
/// # Errors
/// Only if the writer fails.
pub fn write_report<W: Write>(config: &WaveformConfig, out: &mut W) -> fmt::Result {
    write_header(config, out)?;
    for mode in [PatientMode::Adult, PatientMode::Child] {
        write_mode_table(config, mode, out)?;
    }
    write_shortfalls(config, out)?;
    write_sanity(config, out)
}

fn write_header<W: Write>(c: &WaveformConfig, out: &mut W) -> fmt::Result {
    writeln!(out, "# Shock design table: MODEL, NOT A MEASUREMENT")?;
    writeln!(out)?;
    writeln!(
        out,
        "Generated by `cargo run -p aed-waveform --example design_table` from the default \
         `WaveformConfig`. Do not edit by hand: a test fails if this file and the code disagree."
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "**Every number here is a simulated result from an idealised electrical model. \
         Nothing has been measured: no hardware exists.** NOT A MEDICAL DEVICE; nothing here is \
         safe or ready for use on a person or animal (see SAFETY.md). This is design input only, \
         not build instructions."
    )?;
    writeln!(out)?;
    writeln!(out, "## Design inputs")?;
    writeln!(out)?;
    writeln!(out, "| Input | Value | Status |")?;
    writeln!(out, "|---|---|---|")?;
    writeln!(
        out,
        "| Storage capacitor | {:.0} µF | Design point (D-02, research notes Q4) |",
        c.capacitance_uf
    )?;
    writeln!(
        out,
        "| Device internal resistance | {:.1} Ω | ASSUMPTION, no parts chosen |",
        c.internal_ohms
    )?;
    writeln!(
        out,
        "| Adult charge voltage | {} V | Chosen; reasoning in `config.rs` |",
        c.adult_charge.0
    )?;
    writeln!(
        out,
        "| Child charge voltage | {} V | Chosen; reasoning in `config.rs` |",
        c.child_charge.0
    )?;
    writeln!(
        out,
        "| Highest allowed charge voltage | {} V | Top of the REQUIREMENTS.md range |",
        c.max_charge.0
    )?;
    writeln!(
        out,
        "| Targets | adult {:.0} J, child {:.0} J delivered | D-03, D-04 |",
        WaveformConfig::target_joules(PatientMode::Adult),
        WaveformConfig::target_joules(PatientMode::Child)
    )?;
    writeln!(
        out,
        "| Phase 1 | {:.1} to {:.1} ms | Starting assumption (ARCHITECTURE.md) |",
        ms(c.phase1_min),
        ms(c.phase1_max)
    )?;
    writeln!(out, "| Phase 2 | {:.3} × phase 1, kept within {:.1} to {:.1} ms | Starting assumption (ARCHITECTURE.md) |", c.phase2_ratio, ms(c.phase2_min), ms(c.phase2_max))?;
    writeln!(
        out,
        "| Gap between phases | {:.1} ms | ASSUMPTION, depends on switches |",
        ms(c.interphase)
    )?;
    writeln!(
        out,
        "| Whole shock at most | {:.1} ms | Starting assumption (ARCHITECTURE.md) |",
        ms(c.max_total)
    )?;
    writeln!(
        out,
        "| Highest allowed peak current | {:.0} A | PLACEHOLDER until switches are chosen |",
        c.max_peak_current_amps
    )?;
    writeln!(out, "| Energy tolerance | ±{:.0}% | UNVERIFIED placeholder; real figure is in IEC 60601-2-4 (not yet bought) |", c.energy_tolerance * 100.0)?;
    writeln!(out)?;
    writeln!(
        out,
        "The model ignores switch voltage drops, wiring inductance, capacitor leakage and \
         dielectric absorption, and any change in the patient's resistance during the shock. \
         Columns: *Stored* is the energy in the capacitor before the shock; *Peak* is the \
         current at the very start; *Avg 1* is the average current over phase 1; *Tilt 1* is how \
         far the current falls during phase 1; *Left* is the energy still in the capacitor \
         afterwards, which the device dumps internally; *Internal* is the energy lost as heat in \
         the device's own discharge path."
    )
}

fn write_mode_table<W: Write>(c: &WaveformConfig, mode: PatientMode, out: &mut W) -> fmt::Result {
    writeln!(out)?;
    writeln!(
        out,
        "## {} mode: target {:.0} J, charge {} V",
        mode_name(mode),
        WaveformConfig::target_joules(mode),
        c.charge_voltage(mode).0
    )?;
    writeln!(out)?;
    writeln!(out, "| Patient Ω | Charge V | Stored J | Phase 1 ms | Gap ms | Phase 2 ms | Total ms | Peak A | Avg 1 A | Delivered J | Error | Tilt 1 | Left J | Internal J | Note |")?;
    writeln!(
        out,
        "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"
    )?;
    for row in design_table(c).filter(|r| r.mode == mode) {
        let r = &row.result;
        let note = match (row.limit, row.within_tolerance) {
            (_, false) => "OUTSIDE TOLERANCE",
            (Some(LimitHit::ShortestAllowed), true) => "shortest allowed",
            (Some(LimitHit::LongestAllowed), true) => "longest allowed",
            (None, true) => "",
        };
        writeln!(
            out,
            "| {} | {} | {:.1} | {:.3} | {:.3} | {:.3} | {:.3} | {:.1} | {:.1} | {:.1} | {:+.1}% | {:.0}% | {:.1} | {:.1} | {} |",
            row.ohms.0,
            row.plan.charge_voltage.0,
            r.stored_energy_j,
            ms(row.plan.phase1),
            ms(row.plan.interphase),
            ms(row.plan.phase2),
            r.total_s() * 1000.0,
            r.peak_current_a,
            r.phase1_average_current_a,
            r.patient_energy_j,
            // Show anything under 0.05% as +0.0% rather than a stray "-0.0%".
            if libm::fabs(row.error_fraction) < 5e-4 { 0.0 } else { row.error_fraction * 100.0 },
            r.phase1_tilt * 100.0,
            r.residual_energy_j,
            r.internal_energy_j,
            note,
        )?;
    }
    Ok(())
}

fn write_shortfalls<W: Write>(c: &WaveformConfig, out: &mut W) -> fmt::Result {
    writeln!(out)?;
    writeln!(out, "## Where the plan misses the target")?;
    writeln!(out)?;
    writeln!(
        out,
        "Rows where a duration limit stopped the planner from hitting the target exactly \
         (checked at every whole ohm from 25 to 175, not only the rows above):"
    )?;
    writeln!(out)?;
    let mut any = false;
    for mode in [PatientMode::Adult, PatientMode::Child] {
        for kind in [LimitHit::ShortestAllowed, LimitHit::LongestAllowed] {
            let mut worst: Option<DesignRow> = None;
            let (mut first, mut last, mut count, mut outside) = (0_u16, 0_u16, 0_u32, 0_u32);
            for ohms in MIN_PATIENT_OHMS.0..=MAX_PATIENT_OHMS.0 {
                let Some(row) = design_row(c, mode, Ohms(ohms)) else {
                    continue;
                };
                if row.limit != Some(kind) {
                    continue;
                }
                if count == 0 {
                    first = ohms;
                }
                last = ohms;
                count += 1;
                if !row.within_tolerance {
                    outside += 1;
                }
                let worse = match worst {
                    None => true,
                    Some(w) => libm::fabs(row.error_fraction) > libm::fabs(w.error_fraction),
                };
                if worse {
                    worst = Some(row);
                }
            }
            let Some(w) = worst else {
                continue;
            };
            any = true;
            let what = match kind {
                LimitHit::ShortestAllowed => "shortest allowed shock still delivers too much",
                LimitHit::LongestAllowed => "longest allowed shock still delivers too little",
            };
            writeln!(
                out,
                "- {}, {} Ω to {} Ω ({} whole-ohm values): {}. Worst miss {:+.1}% \
                 ({:.1} J against {:.0} J) at {} Ω. Outside the ±{:.0}% tolerance: {}.",
                mode_name(mode),
                first,
                last,
                count,
                what,
                w.error_fraction * 100.0,
                w.result.patient_energy_j,
                w.target_j,
                w.ohms.0,
                c.energy_tolerance * 100.0,
                if outside == 0 {
                    "none"
                } else {
                    "SOME, see table"
                },
            )?;
        }
    }
    if !any {
        writeln!(
            out,
            "- None: every whole-ohm resistance hits its target to the microsecond."
        )?;
    }
    Ok(())
}

fn write_sanity<W: Write>(c: &WaveformConfig, out: &mut W) -> fmt::Result {
    writeln!(out)?;
    writeln!(
        out,
        "## Sanity checks against the one published bench point"
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "The Philips application note (research notes, `waveforms_energy_pads.md`, Q2 and Q4) \
         says its 150 J shock from a 100 µF capacitor into 80 Ω charges to 1,683 V and gives \
         21.0 A peak. That is a manufacturer bench claim, not checked by this project."
    )?;
    writeln!(out)?;
    if let Some(row) = design_row(c, PatientMode::Adult, Ohms(80)) {
        let r = &row.result;
        let cf = c.capacitance_uf * 1e-6;
        let philips_stored = 0.5 * cf * 1683.0 * 1683.0;
        let ideal_peak = r.charge_voltage_v / r.patient_ohms;
        let v_for_21a = 21.0 * r.total_ohms;
        writeln!(out, "| At 80 Ω, adult | Philips (published) | This model |")?;
        writeln!(out, "|---|---:|---:|")?;
        writeln!(
            out,
            "| Charge voltage | 1,683 V | {:.0} V |",
            r.charge_voltage_v
        )?;
        writeln!(
            out,
            "| Stored energy (½·C·V²) | {philips_stored:.1} J | {:.1} J |",
            r.stored_energy_j
        )?;
        writeln!(out, "| Peak current | 21.0 A | {:.1} A |", r.peak_current_a)?;
        writeln!(
            out,
            "| Delivered energy | \"150 J\" (label) | {:.1} J |",
            r.patient_energy_j
        )?;
        writeln!(
            out,
            "| Phase 1 / phase 2 | not published in our notes | {:.2} / {:.2} ms |",
            r.phase1_s * 1000.0,
            r.phase2_s * 1000.0
        )?;
        writeln!(out)?;
        writeln!(out, "What the difference means:")?;
        writeln!(out)?;
        writeln!(
            out,
            "- **Different scheme.** This design charges to one fixed voltage for every adult \
             patient, set high enough to reach 150 J at the 25 Ω and 175 Ω extremes. At 80 Ω it \
             therefore starts higher than Philips does and cuts the shock shorter. Philips' \
             1,683 V may be specific to 80 Ω under its own compensation scheme; the notes do not \
             say whether its voltage is fixed."
        )?;
        writeln!(
            out,
            "- **Internal resistance.** 1,683 V / 80 Ω = 21.04 A exactly, so the Philips figure \
             assumes no internal resistance (or ignores it). Ignoring ours, this model's peak \
             would be {ideal_peak:.1} A. With the assumed {:.0} Ω internal resistance, matching \
             21.0 A at 80 Ω would need {v_for_21a:.0} V.",
            c.internal_ohms
        )?;
        writeln!(
            out,
            "- **The \"150 J\" label.** 1,683 V on 100 µF stores only {philips_stored:.1} J, less \
             than 150 J, so Philips' 150 J cannot be the energy delivered from that charge. It is \
             a nominal or selected-energy label, or the real capacitance differs. The FDA summary \
             (SSED) should settle this. Our 150 J is modelled energy delivered to the patient, \
             which is the stricter meaning."
        )?;
        writeln!(
            out,
            "- **Peak current.** This model gives {:.1} A at 80 Ω, {:+.0}% against Philips. \
             Higher peak current is what Philips argues matters most, but no clinical data in the \
             notes says more is better beyond their level.",
            r.peak_current_a,
            (r.peak_current_a / 21.0 - 1.0) * 100.0
        )?;
    }
    writeln!(out)?;
    writeln!(out, "## Currents that size the hardware")?;
    writeln!(out)?;
    writeln!(out, "| Mode | Peak current at 25 Ω (sizes the output switches) | Peak at 175 Ω | Lowest current during the shock at 175 Ω (end of phase 2) | Current at end of phase 1 at 175 Ω |")?;
    writeln!(out, "|---|---:|---:|---:|---:|")?;
    for mode in [PatientMode::Adult, PatientMode::Child] {
        if let (Some(low), Some(high)) = (
            design_row(c, mode, MIN_PATIENT_OHMS),
            design_row(c, mode, MAX_PATIENT_OHMS),
        ) {
            writeln!(
                out,
                "| {} | {:.1} A | {:.1} A | {:.1} A | {:.1} A |",
                mode_name(mode),
                low.result.peak_current_a,
                high.result.peak_current_a,
                libm::fabs(high.result.phase2_end_current_a),
                high.result.phase1_end_current_a,
            )?;
        }
    }
    writeln!(out)?;
    writeln!(
        out,
        "The research notes give about 78 A at 25 Ω for 1,950 V with no internal resistance; \
         the assumed {:.0} Ω internal resistance brings it down to the figure above. The notes \
         also suggest at least about 10 A at 175 Ω for an adult (background, not re-verified).",
        c.internal_ohms
    )
}
