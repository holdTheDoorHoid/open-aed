"""Write a KiCad 10 ``.kicad_sch`` from a :class:`placement.Layout`."""

from __future__ import annotations

import uuid
from dataclasses import dataclass

from .placement import Layout, PlacedPart
from .sexpr import S, dumps
from .spec import Sheet

FILE_VERSION = "20260306"  # KiCad 10.0 schematic format
GENERATOR = "aed_schgen"
NS = uuid.UUID("6f1f7a52-6c0b-4a57-9d43-1c5b0f6d2a10")


def uid(*parts: str) -> str:
    """Deterministic UUID, so regenerating an unchanged spec gives an identical file."""
    return str(uuid.uuid5(NS, "/".join(parts)))


@dataclass
class Instance:
    """One placement of a sheet in the hierarchy."""

    path: str  # "/<root uuid>/<sheet-symbol uuid>"; "/<root uuid>" for the root itself
    ref_offset: int = 0
    page: str = "1"


def offset_ref(ref: str, off: int) -> str:
    if not off:
        return ref
    i = len(ref)
    while i and ref[i - 1].isdigit():
        i -= 1
    return f"{ref[:i]}{int(ref[i:]) + off}"


def font(size: float = 1.27, bold: bool = False) -> list:
    f = [S("font"), [S("size"), size, size]]
    if bold:
        f.append([S("bold"), S("yes")])
    return f


def effects(size: float = 1.27, justify: list | None = None, hide: bool = False, bold: bool = False) -> list:
    e = [S("effects"), font(size, bold)]
    if justify:
        e.append([S("justify"), *[S(j) for j in justify]])
    if hide:
        e.append([S("hide"), S("yes")])
    return e


def prop(name: str, value: str, x: float, y: float, angle: int = 0, hide: bool = False,
         justify: list | None = None, size: float = 1.27) -> list:
    node = [S("property"), name, value, [S("at"), x, y, angle]]
    if hide:
        node.append([S("hide"), S("yes")])
    node += [[S("show_name"), S("no")], [S("do_not_autoplace"), S("no")], effects(size, justify)]
    return node


def title_block(sheet: Sheet, project_title: str) -> list:
    tb = [S("title_block"), [S("title"), sheet.title], [S("date"), sheet.date],
          [S("rev"), sheet.revision], [S("company"), sheet.company or project_title]]
    comments = list(sheet.comments)
    if sheet.source:
        comments.insert(0, f"Source: {sheet.source}")
    if sheet.notice:
        comments.insert(0, sheet.notice)
    comments.append("Generated by tools/schgen from the sheet spec — edit the spec, not this file (until schematic freeze)")
    for i, c in enumerate(comments[:9], 1):
        tb.append([S("comment"), i, c])
    return tb


def _symbol_node(pp: PlacedPart, sym, sheet: Sheet, instances: list[Instance], project: str) -> list:
    p = pp.part
    u = uid(sheet.name, "sym", p.ref) if pp.unit == 1 else uid(sheet.name, "sym", p.ref, str(pp.unit))
    node = [S("symbol"), [S("lib_id"), pp.lib_id], [S("at"), pp.x, pp.y, pp.rot], [S("unit"), pp.unit],
            [S("body_style"), 1], [S("exclude_from_sim"), S("no")], [S("in_bom"), S("yes")],
            [S("on_board"), S("yes")], [S("in_pos_files"), S("yes")], [S("dnp"), S("yes" if p.dnp else "no")],
            [S("uuid"), u]]
    fld_angle = 90 if pp.rot in (90, 270) else 0  # keep field text horizontal on a rotated symbol
    rj = None if pp.rot in (90, 270) and len(p.pins) == 2 else ["left"]
    node.append(prop("Reference", p.ref, pp.ref_at[0], pp.ref_at[1], fld_angle, justify=rj))
    node.append(prop("Value", p.value, pp.val_at[0], pp.val_at[1], fld_angle, justify=rj))
    hidden = [
        ("Footprint", p.footprint),
        ("Datasheet", p.datasheet or sym.properties.get("Datasheet", "")),
        ("Description", p.description or sym.properties.get("Description", "")),
        ("MPN", p.mpn),
        ("Manufacturer", p.manufacturer),
        ("Variant", p.variant),
    ]
    if p.footprint_todo:
        hidden.append(("FootprintStatus", "needs creating"))
    hidden += sorted(p.fields.items())
    for k, v in hidden:
        node.append(prop(k, v, pp.x, pp.y, 0, hide=True))
    for pm in p.pins:
        if pm.number in pp.pins:
            node.append([S("pin"), pm.number, [S("uuid"), uid(sheet.name, "pin", p.ref, pm.number)]])
    paths = [[S("path"), inst.path, [S("reference"), offset_ref(p.ref, inst.ref_offset)], [S("unit"), pp.unit]]
             for inst in instances]
    node.append([S("instances"), [S("project"), project, *paths]])
    return node


def _power_node(ps, sheet: Sheet, instances: list[Instance], project: str, idx: int) -> list:
    u = uid(sheet.name, "pwr", ps.ref, str(idx), ps.net)
    val = "PWR_FLAG" if ps.is_flag else ps.net
    if ps.dx:
        # centred text placed clear of the sideways symbol (justification would rotate with it)
        vx, vy, just = placement_rnd(ps.x + ps.dx * (5.0 + len(ps.net) * 0.55)), ps.y, None
    else:
        vx, vy, just = ps.x, ps.y + ps.dy * (6.35 if ps.is_flag else 5.08), None
    vang = 90 if ps.rot in (90, 270) else 0  # field angles are relative to the symbol
    node = [S("symbol"), [S("lib_id"), ps.lib_id], [S("at"), ps.x, ps.y, ps.rot], [S("unit"), 1],
            [S("body_style"), 1], [S("exclude_from_sim"), S("no")], [S("in_bom"), S("yes")],
            [S("on_board"), S("yes")], [S("in_pos_files"), S("yes")], [S("dnp"), S("no")], [S("uuid"), u],
            prop("Reference", ps.ref, ps.x, ps.y, 0, hide=True),
            prop("Value", val, vx, vy, vang, justify=just, hide=(val.upper() == "GND")),
            prop("Footprint", "", ps.x, ps.y, 0, hide=True),
            prop("Datasheet", "", ps.x, ps.y, 0, hide=True),
            prop("Description", "", ps.x, ps.y, 0, hide=True),
            [S("pin"), "1", [S("uuid"), uid(sheet.name, "pwrpin", ps.ref, str(idx))]]]
    # each instance of a multi-instance sheet needs its own power-symbol reference, or ERC sees one
    # symbol twice (e.g. a PWR_FLAG "connected to itself")
    paths = [[S("path"), inst.path, [S("reference"), offset_ref(ps.ref, k * 100000)], [S("unit"), 1]]
             for k, inst in enumerate(instances)]
    node.append([S("instances"), [S("project"), project, *paths]])
    return node


def placement_rnd(v: float) -> float:
    return round(v, 4)


def _stroke(width: float = 0, kind: str = "solid") -> list:
    return [S("stroke"), [S("width"), width], [S("type"), S(kind)]]


def build(sheet: Sheet, lay: Layout, libs, instances: list[Instance], project: str, project_title: str,
          sheet_uuid: str, is_root: bool = False, extra_items: list | None = None,
          extra_lib_ids: list[str] | None = None) -> list:
    root = [S("kicad_sch"), [S("version"), S(FILE_VERSION)], [S("generator"), GENERATOR],
            [S("generator_version"), "1.0"], [S("uuid"), sheet_uuid]]
    if lay.paper == "User":
        root.append([S("paper"), "User", lay.width, lay.height])
    else:
        root.append([S("paper"), lay.paper])
    root.append(title_block(sheet, project_title))

    lib_ids = sorted({pp.lib_id for pp in lay.parts} | {ps.lib_id for ps in lay.power} | set(extra_lib_ids or []))
    lib_symbols = [S("lib_symbols")]
    for lid in lib_ids:
        lib_symbols.append(libs.get(lid).embedded())
    root.append(lib_symbols)

    for i, (x1, y1, x2, y2) in enumerate(lay.frames):
        root.append([S("rectangle"), [S("start"), x1, y1], [S("end"), x2, y2], _stroke(0.254, "dash"),
                     [S("fill"), [S("type"), S("none")]], [S("uuid"), uid(sheet.name, "frame", str(i))]])
    for i, tb in enumerate(lay.boxes):
        root.append([S("text_box"), tb.text, [S("exclude_from_sim"), S("no")], [S("at"), tb.x, tb.y, 0],
                     [S("size"), tb.w, tb.h], [S("margins"), 0.9525, 0.9525, 0.9525, 0.9525],
                     _stroke(0 if tb.border else -1, "solid" if tb.border else "default"),
                     [S("fill"), [S("type"), S("none")]], effects(tb.size, ["left", "top"], bold=tb.bold),
                     [S("uuid"), uid(sheet.name, "textbox", str(i))]])
    for i, nc in enumerate(lay.noconnects):
        root.append([S("no_connect"), [S("at"), nc.x, nc.y], [S("uuid"), uid(sheet.name, "nc", str(i))]])
    for i, w in enumerate(lay.wires):
        root.append([S("wire"), [S("pts"), [S("xy"), w.x1, w.y1], [S("xy"), w.x2, w.y2]], _stroke(),
                     [S("uuid"), uid(sheet.name, "wire", str(i))]])
    for i, lb in enumerate(lay.labels):
        just = ["right"] if lb.angle == 180 else ["left"]
        u = [S("uuid"), uid(sheet.name, "label", str(i), lb.net)]
        if lb.kind == "local":
            root.append([S("label"), lb.net, [S("at"), lb.x, lb.y, lb.angle],
                         [S("fields_autoplaced"), S("yes")], effects(1.27, just + ["bottom"]), u])
        elif lb.kind == "global":
            root.append([S("global_label"), lb.net, [S("shape"), S(lb.shape)], [S("at"), lb.x, lb.y, lb.angle],
                         [S("fields_autoplaced"), S("yes")], effects(1.27, just), u])
        else:
            root.append([S("hierarchical_label"), lb.net, [S("shape"), S(lb.shape)],
                         [S("at"), lb.x, lb.y, lb.angle], [S("fields_autoplaced"), S("yes")],
                         effects(1.27, just), u])
    for pp in lay.parts:
        root.append(_symbol_node(pp, libs.get(pp.lib_id), sheet, instances, project))
    for i, ps in enumerate(lay.power):
        root.append(_power_node(ps, sheet, instances, project, i))
    for item in extra_items or []:
        root.append(item)
    if is_root:
        root.append([S("sheet_instances"), [S("path"), "/", [S("page"), "1"]]])
    root.append([S("embedded_fonts"), S("no")])
    return root


def write(path: str, node: list) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(dumps(node))
        fh.write("\n")
