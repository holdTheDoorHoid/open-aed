"""Writes the ngspice control scripts stack_static_wpf.ctl and stack_dynamic_wpf.ctl.

Why a generator: ngspice 42's control language does not substitute a foreach variable used as an alterparam
VALUE inside nested loops ("alterparam fs1=" errors), and silently runs the unaltered circuit. Every alteration
is therefore written out literally. Run:  python3 gen_ctl.py   (then bash run.sh)."""

HDR = ("* NOT FOR CONSTRUCTION — unreviewed design. Simulated results; models as stated; nothing has been built or "
       "measured.\n* SPDX-License-Identifier: CERN-OHL-S-2.0\n* GENERATED by gen_ctl.py - edit that file, not this one.\n")

CORNERS = {
    # name: (tf, leakt, ilk, rating)   IXYS DS100418B Fig. 12 readings; leakage log-interpolated [EST]
    "cold": ("0.89", "262meg", "0.5u", 1666),
    "nom": ("1.0", "68meg", "5u", 1700),
    "hot": ("1.11", "17.7meg", "50u", 1700),
}

def corner(name):
    tf, lk, ilk, rat = CORNERS[name]
    return (f"alterparam tf = {tf}\nalterparam leakt = {lk}\nalterparam ilk = {ilk}\nset tn = {name}\n"
            f"set rat = {rat}\n")

def randomise_static():
    s = "  let u = sunif(vector(36))\n"
    names = [f"ts{k}" for k in range(1, 5)] + [f"tr{k}" for k in range(1, 5)] + \
            [f"tg{k}" for k in range(2, 5)] + [f"tb{k}" for k in range(2, 5)] + [f"tp{k}" for k in range(1, 5)]
    i = 0
    for n in names:
        s += f"  let a{i} = 1 + 0.02*u[{i}]\n  alterparam {n} = $&a{i}\n"
        i += 1
    for k in range(1, 5):
        s += f"  let a{i} = -3 + u[{i}]\n  alterparam vo{k} = $&a{i}\n"
        i += 1
    for k in range(1, 5):
        s += f"  let a{i} = 0.51 + 0.49*u[{i}]\n  alterparam lk{k} = $&a{i}\n"
        i += 1
    for k in range(2, 5):
        s += f"  let a{i} = 0.5 + 0.5*u[{i}]\n  alterparam dl{k} = $&a{i}\n"
        i += 1
    return s

SOLVE = ("  reset\n  dc VCAP 0 {v} {stp}\n  let nl = length(v(vdsmax)) - 1\n  let cur = v(vdsmax)[nl]\n"
         "  let x1 = v(vds1)[nl]\n  let x2 = v(vds2)[nl]\n  let x3 = v(vds3)[nl]\n  let x4 = v(vds4)[nl]\n"
         "  let x5 = v(vdrmax)[nl]\n  let x6 = v(vdfmax)[nl]\n  let x7 = v(vsmax)[nl]\n  let x8 = v(vgsmax)[nl]\n"
         "  let x9 = -i(vcap)[nl]\n")
DETAIL = ('v1=$&x1 v2=$&x2 v3=$&x3 v4=$&x4 diode_rev=$&x5 feed_100k=$&x6 string_elem=$&x7 vgs_upper=$&x8 '
          'I_path_A=$&x9')

def mc_block(label, nruns, v, setup="", teardown="", per_run_fault=False):
    s = f"* ---- {label}, {nruns} runs at {v} V\nset worst = 0\nset wdet = none\nset run = 0\nwhile $run < {nruns}\n"
    s += randomise_static()
    if per_run_fault:
        s += ("  let kk = floor((u[35]+1)*2) + 1\n  if kk > 4\n    let kk = 4\n  end\n  set kks = $&kk\n"
              "  alterparam fq$kks = 1\n")
    s += setup
    s += SOLVE.format(v=v, stp=v/110)
    s += (f"  if cur > $worst\n    set worst = $&cur\n    set wdet = \"{DETAIL}\"\n  end\n")
    if per_run_fault:
        s += "  alterparam fq$kks = 0\n"
    s += "  let tmp = $run + 1\n  set run = $&tmp\nend\n"
    s += teardown
    s += (f"let mg = 1 - $worst/$rat\necho \"STATIC {label} T=$tn V={v} runs={nruns} worst_vds=$worst rating=$rat "
          f"margin=$&mg | $wdet\"\n")
    return s

FAULTS = ([(f"fq{k}", m) for k in range(1, 5) for m in (1, 2)] + [(f"fs{k}", m) for k in range(1, 5) for m in (1, 2)]
          + [(f"fr{k}", m) for k in range(1, 5) for m in (1, 2)] + [(f"fc{k}", 1) for k in range(1, 5)]
          + [(f"fsc{k}", 1) for k in range(1, 5)] + [(f"fg{k}", m) for k in range(2, 5) for m in (1, 2)]
          + [(f"fd{k}", m) for k in range(2, 5) for m in (1, 2)] + [(f"fb{k}", m) for k in range(2, 5) for m in (1, 2)]
          + [(f"fgs{k}", m) for k in range(2, 5) for m in (1, 2)] + [(f"ft{k}", m) for k in range(1, 5) for m in (1, 2)])
MODE = {1: "short", 2: "open"}

def static_ctl(nmc=200, nfault=20, corners=("cold", "hot"), parts_ab=True):
    s = HDR + """* Control script for stack_static_wpf.cir. Each solution is a DC sweep of the capacitor voltage from 0 V
* (continuation): a plain operating-point solve fails to converge for several fault cases and ngspice's fallback then
* returns an unsettled pseudo-transient state without saying so (found while writing these runs).
* Corners (IXYS DS100418B Fig. 12 read 2026-11-27; leakage log-interpolated [EST]): cold -20 C |VGS(off)| x0.89,
* rating 1,666 V; nom 25 C; hot 70 C x1.11, rating 1,700 V, GP02 leakage 50 uA (its 100 C maximum: bounding).
* Monte Carlo (uniform): 4.7 M, 10 M, 22 M, 100 M resistors +-2 %; VGS(off) -2..-4 V x corner factor; device leakage
* 2-100 % of the corner maximum; GP02 leakage 0-100 % of the corner value (dl 0.5..1 x2 range, see netlist).
.control
set noaskquit
set rndseed = 20261128
option reltol=1e-4
"""
    if parts_ab:
      s += "* ==== A: nominal parts\n"
    for c in (("cold", "nom", "hot") if parts_ab else ()):
        s += corner(c)
        for v in (1950, 2200):
            s += SOLVE.format(v=v, stp=v/110).replace("  ", "")
            s += f'echo "STATIC nominal_parts T=$tn V={v} runs=1 worst_vds=$&cur | {DETAIL}"\n'
    if parts_ab:
      s += "* ==== B: hot steering-diode leakage, deterministic: no fault and device 2 shorted\n" + corner("hot")
    for il in (("0", "5u", "50u", "200u") if parts_ab else ()):
        s += f"alterparam ilk = {il}\nalterparam fq2 = 0\n" + SOLVE.format(v=2200, stp=20).replace("  ", "")
        s += "set anf = $&cur\nalterparam fq2 = 1\n" + SOLVE.format(v=2200, stp=20).replace("  ", "")
        s += (f'echo "STATIC hot_GP02_leakage ilk={il} T=hot V=2200 no_fault={"$"}anf device2_shorted=$&cur | '
              f'{DETAIL}"\nalterparam fq2 = 0\n')
    s += "* ==== C: Monte Carlo without and with one shorted device; then every single part fault\n"
    for c in corners:
        s += corner(c)
        for v in (1950, 2200):
            s += mc_block("no_fault", nmc, v)
            s += mc_block("one_random_device_shorted", nmc, v, per_run_fault=True)
        for name, m in FAULTS:
            s += mc_block(f"{name}_{MODE[m]}", nfault, 2200, setup=f"  alterparam {name} = {m}\n",
                          teardown=f"alterparam {name} = 0\n")
    s += "* ==== D: the change order's single 4.7 M string element (pstr = 1), one element open, nominal parts\n"
    s += "alterparam pstr = 1\n"
    for c in ("cold", "hot"):
        s += corner(c)
        for k in range(1, 5):
            s += f"alterparam fs{k} = 2\n" + SOLVE.format(v=2200, stp=20).replace("  ", "")
            s += (f'echo "STATIC AS_CHANGE_ORDER_single_4.7M_element{k}_OPEN T=$tn V=2200 worst_vds=$&cur rating=$rat | '
                  f'{DETAIL}"\nalterparam fs{k} = 0\n')
        s += SOLVE.format(v=2200, stp=20).replace("  ", "")
        s += f'echo "STATIC AS_CHANGE_ORDER_single_4.7M_no_fault T=$tn V=2200 worst_vds=$&cur | {DETAIL}"\n'
        s += "alterparam fq2 = 1\n" + SOLVE.format(v=2200, stp=20).replace("  ", "")
        s += f'echo "STATIC AS_CHANGE_ORDER_single_4.7M_device2_shorted T=$tn V=2200 worst_vds=$&cur | {DETAIL}"\n'
        s += "alterparam fq2 = 0\n"
    s += "alterparam pstr = 0\n"
    s += "quit\n.endc\n"
    return s

def dynamic_ctl(nmc=40):
    s = HDR + """* Control script for stack_dynamic_wpf.cir (events in the netlist header). C0G +-5 % (KEMET J tolerance).
.control
set noaskquit
set rndseed = 20261129
option reltol=1e-4
"""
    meas = ("reset\ntran 0.2u 0.5 0 20u uic\nmeas tran s1 max v(xa.vdm) from=99m to=110m\n"
            "meas tran sdc find v(xa.vdm) at=0.24\nmeas tran s2 max v(xa.vdm) from=0.24 to=0.30\n"
            "meas tran s3 max v(xa.vdm) from=0.44 to=0.5\nlet cur = max(max(s1,s2),s3)\n")
    for c in ("cold", "hot"):
        s += corner(c)
        for k in range(1, 5):
            s += f"alterparam vo{k} = -3\nalterparam lk{k} = 0.3\nalterparam sh{k} = 0\n"
        for low in range(1, 5):
            for k in range(1, 5):
                val = "0.95" if k == low else "1.05"
                s += f"alterparam cs{k} = {val}\nalterparam cd{k} = {val}\n"
            s += meas
            s += (f'let mg = 1 - cur/$rat\necho "DYN worst_C0G_pattern_low_at_{low} T=$tn | step 1000->2200 V in 1 us: '
                  f'$&s1 | settled 2200 V: $&sdc | 2200->1200 V in 10 ms: $&s2 | 1200->2200 V in 2 ms: $&s3 | '
                  f'worst=$&cur rating=$rat margin=$&mg"\n')
        s += f"set worst = 0\nset wdet = none\nset run = 0\nwhile $run < {nmc}\n  let u = sunif(vector(16))\n"
        i = 0
        for k in range(1, 5):
            for nm, expr in ((f"cs{k}", "1 + 0.05*u[{i}]"), (f"cd{k}", "1 + 0.05*u[{i}]"),
                             (f"vo{k}", "-3 + u[{i}]"), (f"lk{k}", "0.51 + 0.49*u[{i}]")):
                s += f"  let a{i} = {expr.format(i=i)}\n  alterparam {nm} = $&a{i}\n"
                i += 1
        s += "  " + meas.replace("\n", "\n  ").rstrip() + "\n"
        s += ('  if cur > $worst\n    set worst = $&cur\n    set wdet = "step=$&s1 fall=$&s2 rise2ms=$&s3"\n  end\n'
              "  let tmp = $run + 1\n  set run = $&tmp\nend\n")
        s += (f'let mg = 1 - $worst/$rat\necho "DYN montecarlo_{nmc} T=$tn worst_vds=$worst rating=$rat margin=$&mg | '
              f'$wdet"\n')
        for k in range(1, 5):
            s += f"alterparam vo{k} = -3\nalterparam lk{k} = 0.3\n"
        for sh in range(1, 5):
            low = sh - 1 if sh > 1 else 2
            for k in range(1, 5):
                val = "0.95" if k == low else "1.05"
                s += f"alterparam cs{k} = {val}\nalterparam cd{k} = {val}\n"
            s += f"alterparam sh{sh} = 1\n" + meas
            s += (f'let mg = 1 - cur/$rat\necho "DYN device{sh}_shorted(low C0G on device {low}) T=$tn | step: $&s1 | '
                  f'settled: $&sdc | fall: $&s2 | rise 2 ms: $&s3 | worst=$&cur rating=$rat margin=$&mg"\n'
                  f"alterparam sh{sh} = 0\n")
    s += "quit\n.endc\n"
    return s

if __name__ == "__main__":
    import sys
    quick = len(sys.argv) > 1 and sys.argv[1] == "quick"
    open("stack_static_wpf.ctl", "w").write(static_ctl(20 if quick else 100, 3 if quick else 12))
    open("stack_dynamic_wpf.ctl", "w").write(dynamic_ctl(4 if quick else 40))
    if len(sys.argv) > 1 and sys.argv[1] == "split":
        # two halves for running in parallel on a busy machine (same cases, same seed per half)
        open("out/static_cold.ctl", "w").write(static_ctl(100, 12, ("cold",), True))
        open("out/static_hot.ctl", "w").write(static_ctl(100, 12, ("hot",), False))
    print("wrote stack_static_wpf.ctl, stack_dynamic_wpf.ctl")
